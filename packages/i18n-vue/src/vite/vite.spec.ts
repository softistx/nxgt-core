const roots: string[] = [];
afterEach(() => {
	for (const root of roots.splice(0))
		rmSync(root, { recursive: true, force: true });
});

function project(): string {
	const root = mkdtempSync(join(tmpdir(), 'i18n-vue-vite-'));
	roots.push(root);
	mkdirSync(join(root, 'locales'));
	writeFileSync(
		join(root, 'locales/en.json'),
		'{ "home": { "greeting": "Hi {name}" } }',
	);
	writeFileSync(
		join(root, 'locales/fr.json'),
		'{ "home": { "greeting": "Salut {name}" } }',
	);
	return root;
}

type Hooks = {
	configResolved(config: unknown): void;
	buildStart(): Promise<void>;
	configureServer(server: unknown): void;
};

/** The plugin's hooks, run the way Vite runs them. */
const start = async (plugin: unknown, root: string) => {
	const hooks = plugin as Hooks;
	hooks.configResolved({ root });
	await hooks.buildStart();
	return hooks;
};

/** Lets a fire-and-forget regeneration (a watcher event handler) settle. */
const flush = () => new Promise<void>((resolve) => setImmediate(resolve));

/** The generated file for project()'s catalogues, as it was before `lazy` existed. */
const EAGER_TYPES = [
	'// Generated by @nxgt/i18n-vue from the en catalogue.',
	'// Never edited, never committed: it types t() from the catalogues.',
	"import type {} from '@nxgt/i18n-vue';",
	'',
	"declare module '@nxgt/i18n-vue' {",
	'\tinterface I18nMessages {',
	"\t\t'home.greeting': { name: string | number };",
	'\t}',
	'\tinterface I18nLocales {',
	"\t\t'en': true;",
	"\t\t'fr': true;",
	'\t}',
	'}',
	'',
].join('\n');

type Hook =
	| ((...args: unknown[]) => unknown)
	| { handler: (...args: unknown[]) => unknown }
	| undefined;

/** What a hook answers, run the way Vite runs it — `undefined` when the plugin has no such hook. */
const run = (hook: unknown, ...args: unknown[]): unknown => {
	const it = hook as Hook;
	if (it === undefined) return undefined;
	return typeof it === 'function' ? it(...args) : it.handler(...args);
};

describe('i18nTypes without lazy (characterization)', () => {
	test('serves no module: resolveId and load answer nothing', async () => {
		const root = project();
		const plugin = i18nTypes({ locales: ['en', 'fr'] });
		await start(plugin, root);
		const { resolveId, load } = plugin as {
			resolveId?: unknown;
			load?: unknown;
		};
		for (const id of [
			'virtual:@nxgt/i18n-vue/catalogues',
			'virtual:@nxgt/i18n-vue/locale/fr',
		]) {
			expect(await run(resolveId, id)).toBeUndefined();
			expect(await run(load, id)).toBeUndefined();
			expect(await run(load, `\0${id}`)).toBeUndefined();
		}
	});

	test('writes the same declaration file, byte for byte', async () => {
		const root = project();
		await start(i18nTypes({ locales: ['en', 'fr'] }), root);
		expect(readFileSync(join(root, 'src/generated/i18n.d.ts'), 'utf8')).toBe(
			EAGER_TYPES,
		);
	});
});

describe('i18nTypes', () => {
	test('writes src/generated/i18n.d.ts from the catalogues when the build starts', async () => {
		const root = project();
		await start(i18nTypes({ locales: ['en', 'fr'] }), root);
		const types = readFileSync(join(root, 'src/generated/i18n.d.ts'), 'utf8');
		expect(types).toContain("\t\t'home.greeting': { name: string | number };");
		expect(types).toContain("\t\t'fr': true;");
	});

	test('writes where out says', async () => {
		const root = project();
		await start(
			i18nTypes({ locales: ['en', 'fr'], out: 'types/i18n.d.ts' }),
			root,
		);
		expect(readFileSync(join(root, 'types/i18n.d.ts'), 'utf8')).toStartWith(
			'// Generated by @nxgt/i18n-vue',
		);
	});

	test('fails the build on a catalogue that cannot be right', async () => {
		const root = project();
		writeFileSync(join(root, 'locales/fr.json'), '{ "home": {} }');
		await expectThrowAsync(
			() => start(i18nTypes({ locales: ['en', 'fr'] }), root),
			Error,
			'i18n: fr: home.greeting is missing — en, the fallback locale, has it',
		);
	});

	test('rewrites the types when a catalogue changes in vite dev, and reports a broken one', async () => {
		const root = project();
		const hooks = await start(i18nTypes({ locales: ['en', 'fr'] }), root);
		const watcher = Object.assign(new EventEmitter(), { add: () => {} });
		const errors: string[] = [];
		hooks.configureServer({
			watcher,
			config: { logger: { error: (message: string) => errors.push(message) } },
		});
		writeFileSync(
			join(root, 'locales/en.json'),
			'{ "home": { "greeting": "Hi {name}", "bye": "Bye" } }',
		);
		writeFileSync(
			join(root, 'locales/fr.json'),
			'{ "home": { "greeting": "Salut {name}", "bye": "Salut" } }',
		);
		watcher.emit('change', join(root, 'locales/fr.json'));
		await flush();
		const file = join(root, 'src/generated/i18n.d.ts');
		expect(readFileSync(file, 'utf8')).toContain("'home.bye': { };");

		writeFileSync(
			join(root, 'locales/fr.json'),
			'{ "home": { "greeting": "Salut {name}" } }',
		);
		watcher.emit('change', join(root, 'locales/fr.json'));
		await flush();
		expect(errors).toEqual([
			'i18n: fr: home.bye is missing — en, the fallback locale, has it',
		]);
		expect(readFileSync(file, 'utf8')).toContain("'home.bye': { };");

		watcher.emit('change', join(root, 'src/main.ts'));
		await flush();
		expect(errors).toHaveLength(1);
	});

	test('refuses a wiring mistake with a TypeError', () => {
		expectThrow(
			() => i18nTypes({ locales: [] }),
			TypeError,
			"i18nTypes: locales must hold at least one locale, as ['en', 'fr']",
		);
		expectThrow(
			() => i18nTypes({ locales: ['en'], out: 'src/i18n.ts' }),
			TypeError,
			'i18nTypes: out must be the path of a .d.ts file, as src/generated/i18n.d.ts',
		);
	});

	test('reads a folder catalogue too, the file path a key prefix', async () => {
		const root = project();
		mkdirSync(join(root, 'locales/en'));
		mkdirSync(join(root, 'locales/fr'));
		writeFileSync(join(root, 'locales/en/mails.json'), '{ "title": "Mail" }');
		writeFileSync(
			join(root, 'locales/fr/mails.json'),
			'{ "title": "Courriel" }',
		);
		await start(i18nTypes({ locales: ['en', 'fr'] }), root);
		const types = readFileSync(join(root, 'src/generated/i18n.d.ts'), 'utf8');
		expect(types).toContain("\t\t'mails.title': { };");
	});

	test('reads the resources object of a messages module', async () => {
		const root = project();
		mkdirSync(join(root, 'i18n'));
		writeFileSync(
			join(root, 'i18n/messages.ts'),
			"export default { en: { a: 'A {name}' }, fr: { a: 'A {name}' } };",
		);
		await start(
			i18nTypes({ locales: ['en', 'fr'], messages: './i18n/messages.ts' }),
			root,
		);
		const types = readFileSync(join(root, 'src/generated/i18n.d.ts'), 'utf8');
		expect(types).toContain("\t\t'a': { name: string | number };");
	});
});

const CATALOGUES = 'virtual:@nxgt/i18n-vue/catalogues';
const LOCALE = 'virtual:@nxgt/i18n-vue/locale/';

/** What `load` serves for `id`, resolved through the plugin's own `resolveId`. */
const serve = async (plugin: unknown, id: string): Promise<string> => {
	const { resolveId, load } = plugin as { resolveId: unknown; load: unknown };
	const resolvedId = await run(resolveId, id);
	expect(resolvedId).toBe(`\0${id}`);
	return (await run(load, resolvedId)) as string;
};

/** The catalogue a locale module's source exports. */
const exported = (source: string): unknown => {
	expect(source).toStartWith('export default ');
	return JSON.parse(source.slice('export default '.length, -';\n'.length));
};

/** The modules the catalogues module's source exports, imported from a file. */
const importSource = async (root: string, source: string) => {
	const file = join(root, `catalogues-${Math.random()}.mjs`);
	writeFileSync(file, source);
	return import(file);
};

/** The declaration file `lazy` writes beside the default `out`. */
const LAZY_TYPES = [
	'// Generated by @nxgt/i18n-vue from the en catalogue.',
	'// Never edited, never committed: it types t() from the catalogues.',
	'// The modules i18nTypes({ lazy: true }) serves. A script, not a module: only a script declares one.',
	'',
	"declare module 'virtual:@nxgt/i18n-vue/catalogues' {",
	"\timport type { CatalogueLoaders, Catalogues, Locale } from '@nxgt/i18n-vue';",
	'\t/** The reference locale: its catalogue is in `catalogues`. */',
	'\texport const fallbackLocale: Locale;',
	'\t/** Every locale, in the order i18nTypes was given them. */',
	'\texport const locales: readonly Locale[];',
	"\t/** The fallback locale's catalogue, inline. */",
	'\texport const catalogues: Catalogues;',
	'\t/** One loader per other locale, each its own chunk. */',
	'\texport const loaders: CatalogueLoaders;',
	'}',
	'',
	"declare module 'virtual:@nxgt/i18n-vue/locale/*' {",
	"\timport type { Catalogue } from '@nxgt/i18n-vue';",
	'\tconst catalogue: Catalogue;',
	'\texport default catalogue;',
	'}',
	'',
].join('\n');

/** A `vite dev` server, as far as the plugin reads it, recording what it does. */
function devServer() {
	const watcher = Object.assign(new EventEmitter(), { add: () => {} });
	const errors: string[] = [];
	const invalidated: string[] = [];
	const sent: unknown[] = [];
	const known = new Set<string>();
	const server = {
		watcher,
		config: { logger: { error: (message: string) => errors.push(message) } },
		moduleGraph: {
			getModuleById: (id: string) => (known.has(id) ? { id } : undefined),
			invalidateModule: (module: { id: string }) => invalidated.push(module.id),
		},
		ws: { send: (payload: unknown) => sent.push(payload) },
	};
	return { server, watcher, errors, invalidated, sent, known };
}

describe('i18nTypes with lazy', () => {
	test('serves the fallback catalogue inline, and one dynamic import per other locale', async () => {
		const root = project();
		writeFileSync(
			join(root, 'locales/de.json'),
			'{ "home": { "greeting": "Hallo {name}" } }',
		);
		const plugin = i18nTypes({ locales: ['en', 'fr', 'de'], lazy: true });
		await start(plugin, root);
		const source = await serve(plugin, CATALOGUES);
		expect(source.match(/import\(/g)).toHaveLength(2);
		expect(source).toContain(`"fr": () => import("${LOCALE}fr")`);
		expect(source).toContain(`"de": () => import("${LOCALE}de")`);
		expect(source).not.toContain('Salut');
		expect(source).not.toContain('Hallo');
		const module = await importSource(root, source);
		expect(module.fallbackLocale).toBe('en');
		expect(module.locales).toEqual(['en', 'fr', 'de']);
		expect(module.catalogues).toEqual({
			en: { home: { greeting: 'Hi {name}' } },
		});
		expect(Object.keys(module.loaders)).toEqual(['fr', 'de']);
	});

	test("serves a locale's catalogue merged: the folder layout, and the packages' under it", async () => {
		const root = project();
		mkdirSync(join(root, 'locales/en'));
		mkdirSync(join(root, 'locales/fr'));
		writeFileSync(join(root, 'locales/en/mails.json'), '{ "title": "Mail" }');
		writeFileSync(
			join(root, 'locales/fr/mails.json'),
			'{ "title": "Courriel" }',
		);
		const plugin = i18nTypes({
			locales: ['en', 'fr'],
			lazy: true,
			catalogues: [
				{
					en: { ui: { ok: 'OK' }, home: { greeting: 'Hello {name}' } },
					fr: { ui: { ok: "D'accord" }, home: { greeting: 'Bonjour {name}' } },
				},
			],
		});
		await start(plugin, root);
		expect(exported(await serve(plugin, `${LOCALE}fr`))).toEqual({
			ui: { ok: "D'accord" },
			home: { greeting: 'Salut {name}' },
			mails: { title: 'Courriel' },
		});
	});

	test('resolves only its own ids, and the locales it was given', async () => {
		const root = project();
		const plugin = i18nTypes({ locales: ['en', 'fr'], lazy: true });
		await start(plugin, root);
		const { resolveId, load } = plugin as { resolveId: unknown; load: unknown };
		expect(await run(resolveId, `${LOCALE}de`)).toBeUndefined();
		expect(await run(resolveId, './main.ts')).toBeUndefined();
		expect(await run(load, CATALOGUES)).toBeUndefined();
		expect(await run(load, join(root, 'locales/fr.json'))).toBeUndefined();
	});

	test("writes the same types, and the served modules' beside them", async () => {
		const root = project();
		await start(i18nTypes({ locales: ['en', 'fr'], lazy: true }), root);
		expect(readFileSync(join(root, 'src/generated/i18n.d.ts'), 'utf8')).toBe(
			EAGER_TYPES,
		);
		expect(
			readFileSync(join(root, 'src/generated/i18n.catalogues.d.ts'), 'utf8'),
		).toBe(LAZY_TYPES);
	});

	test('writes the served types beside out, wherever it is', async () => {
		const root = project();
		await start(
			i18nTypes({ locales: ['en', 'fr'], out: 'types/i18n.d.ts', lazy: true }),
			root,
		);
		expect(readFileSync(join(root, 'types/i18n.catalogues.d.ts'), 'utf8')).toBe(
			LAZY_TYPES,
		);
	});

	test('in vite dev, a change invalidates the served modules and reloads the page', async () => {
		const root = project();
		const plugin = i18nTypes({ locales: ['en', 'fr'], lazy: true });
		const hooks = await start(plugin, root);
		const dev = devServer();
		dev.known.add(`\0${CATALOGUES}`);
		dev.known.add(`\0${LOCALE}fr`);
		hooks.configureServer(dev.server);
		writeFileSync(
			join(root, 'locales/fr.json'),
			'{ "home": { "greeting": "Coucou {name}" } }',
		);
		dev.watcher.emit('change', join(root, 'locales/fr.json'));
		await flush();
		expect(dev.errors).toEqual([]);
		expect(dev.invalidated).toEqual([`\0${CATALOGUES}`, `\0${LOCALE}fr`]);
		expect(dev.sent).toEqual([{ type: 'full-reload' }]);
		expect(exported(await serve(plugin, `${LOCALE}fr`))).toEqual({
			home: { greeting: 'Coucou {name}' },
		});
	});

	test('in vite dev, a broken change keeps the served modules, and is logged', async () => {
		const root = project();
		const plugin = i18nTypes({ locales: ['en', 'fr'], lazy: true });
		const hooks = await start(plugin, root);
		const dev = devServer();
		dev.known.add(`\0${LOCALE}fr`);
		hooks.configureServer(dev.server);
		writeFileSync(join(root, 'locales/fr.json'), '{ "home": {} }');
		dev.watcher.emit('change', join(root, 'locales/fr.json'));
		await flush();
		expect(dev.errors).toEqual([
			'i18n: fr: home.greeting is missing — en, the fallback locale, has it',
		]);
		expect(dev.invalidated).toEqual([]);
		expect(dev.sent).toEqual([]);
		expect(exported(await serve(plugin, `${LOCALE}fr`))).toEqual({
			home: { greeting: 'Salut {name}' },
		});
	});

	test('without lazy, vite dev invalidates nothing and reloads nothing', async () => {
		const root = project();
		const hooks = await start(i18nTypes({ locales: ['en', 'fr'] }), root);
		const dev = devServer();
		dev.known.add(`\0${CATALOGUES}`);
		hooks.configureServer(dev.server);
		dev.watcher.emit('change', join(root, 'locales/fr.json'));
		await flush();
		expect(dev.invalidated).toEqual([]);
		expect(dev.sent).toEqual([]);
	});

	test('leaves a hand-written i18n.catalogues.d.ts alone, fails the build, and serves nothing', async () => {
		const root = project();
		const file = join(root, 'src/generated/i18n.catalogues.d.ts');
		mkdirSync(join(root, 'src/generated'), { recursive: true });
		writeFileSync(file, "declare module 'mine' {}\n");
		const plugin = i18nTypes({ locales: ['en', 'fr'], lazy: true });
		const message =
			'i18n: src/generated/i18n.catalogues.d.ts was not written by @nxgt/i18n-vue — point the types at a file of their own';
		await expectThrowAsync(() => start(plugin, root), Error, message);
		expect(readFileSync(file, 'utf8')).toBe("declare module 'mine' {}\n");
		const { resolveId, load } = plugin as { resolveId: unknown; load: unknown };
		const id = await run(resolveId, CATALOGUES);
		await expectThrowAsync(async () => run(load, id), Error, message);
		await expectThrowAsync(
			async () => run(load, `\0${LOCALE}fr`),
			Error,
			message,
		);
	});

	test('refuses a lazy that is not a boolean, with a TypeError', () => {
		expectThrow(
			() =>
				i18nTypes({
					locales: ['en', 'fr'],
					lazy: 'yes' as unknown as boolean,
				}),
			TypeError,
			'i18nTypes: lazy must be true or false, as i18nTypes({ locales, lazy: true })',
		);
	});
});

describe('i18nTypes with lazy, under vite build', () => {
	test('splits one chunk per other locale, which createI18n loads', async () => {
		const { build } = await import('vite');
		const root = project();
		writeFileSync(
			join(root, 'locales/de.json'),
			'{ "home": { "greeting": "Hallo {name}" } }',
		);
		writeFileSync(
			join(root, 'main.js'),
			`export { catalogues, fallbackLocale, loaders } from '${CATALOGUES}';\n`,
		);
		await build({
			root,
			configFile: false,
			logLevel: 'silent',
			plugins: [i18nTypes({ locales: ['en', 'fr', 'de'], lazy: true })],
			build: {
				outDir: 'dist',
				minify: false,
				lib: { entry: 'main.js', formats: ['es'], fileName: () => 'main.js' },
			},
		});
		const files = readdirSync(join(root, 'dist'));
		const chunks = files.filter((file) => file !== 'main.js');
		expect(files).toContain('main.js');
		expect(chunks).toHaveLength(2);
		const text = (file: string) =>
			readFileSync(join(root, 'dist', file), 'utf8');
		expect(text('main.js')).not.toContain('Salut');
		expect(text('main.js')).not.toContain('Hallo');
		expect(chunks.filter((file) => text(file).includes('Salut'))).toHaveLength(
			1,
		);
		expect(chunks.filter((file) => text(file).includes('Hallo'))).toHaveLength(
			1,
		);

		const built = await import(join(root, 'dist/main.js'));
		const i18n = createI18n({
			catalogues: built.catalogues,
			loaders: built.loaders,
			fallbackLocale: built.fallbackLocale,
		});
		await i18n.setLocale('de');
		expect(i18n.t('home.greeting', { name: 'Ada' })).toBe('Hallo Ada');
		await i18n.setLocale('fr');
		expect(i18n.t('home.greeting', { name: 'Ada' })).toBe('Salut Ada');
	}, 30_000);
});
