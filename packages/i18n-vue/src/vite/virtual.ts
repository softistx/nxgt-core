/**
 * The modules `i18nTypes({ lazy: true })` serves, and their types: the
 * fallback locale's catalogue inline, every other locale a module of its own
 * that a dynamic `import()` fetches — the `loaders` record `createI18n`
 * takes, produced by the build instead of written by hand.
 */

import type { ViteDevServer } from 'vite';
import { catalogueModuleSource } from '../node/catalogue-module';
import type { LoadedCatalogues } from '../node/load';
import { MARKER } from '../node/types-source';

/** The module an app imports `{ catalogues, loaders }` from. */
export const CATALOGUES_ID = 'virtual:@nxgt/i18n-vue/catalogues';

/** A locale's module: `virtual:@nxgt/i18n-vue/locale/fr`, whose default export is its merged catalogue. */
export const LOCALE_PREFIX = 'virtual:@nxgt/i18n-vue/locale/';

/** Vite's convention: a resolved virtual id starts with `\0`, so no other plugin reads it as a file. */
export const resolved = (id: string): string => `\0${id}`;

/** The id `resolveId` answers for `id`, or `undefined` for an id that is not one of ours or a locale that is not. */
export function resolveVirtual(
	id: string,
	locales: readonly string[],
): string | undefined {
	if (id === CATALOGUES_ID) return resolved(id);
	if (
		id.startsWith(LOCALE_PREFIX) &&
		locales.includes(id.slice(LOCALE_PREFIX.length))
	) {
		return resolved(id);
	}
	return undefined;
}

/** Every resolved id served for `locales`: what `vite dev` invalidates when a catalogue changes. */
export function servedIds(locales: readonly string[]): string[] {
	return [
		resolved(CATALOGUES_ID),
		...locales.map((locale) => resolved(`${LOCALE_PREFIX}${locale}`)),
	];
}

/**
 * The source of `virtual:@nxgt/i18n-vue/catalogues`: `fallbackLocale`,
 * `locales`, `catalogues` (the fallback locale's alone, inline) and
 * `loaders` (one dynamic `import()` per other locale, so a bundler splits
 * each into a chunk of its own).
 */
export function cataloguesModuleSource(loaded: LoadedCatalogues): string {
	const { fallbackLocale, locales, catalogues } = loaded;
	const lazy = locales.filter((locale) => locale !== fallbackLocale);
	return [
		`// Generated by @nxgt/i18n-vue: the ${fallbackLocale} catalogue inline, every other locale on demand.`,
		`export const fallbackLocale = ${JSON.stringify(fallbackLocale)};`,
		`export const locales = ${JSON.stringify(locales)};`,
		`export const catalogues = { ${JSON.stringify(fallbackLocale)}: ${JSON.stringify(catalogues[fallbackLocale])} };`,
		'export const loaders = {',
		...lazy.map(
			(locale) =>
				`\t${JSON.stringify(locale)}: () => import(${JSON.stringify(`${LOCALE_PREFIX}${locale}`)}),`,
		),
		'};',
		'',
	].join('\n');
}

/** Whether `id` is a resolved id of ours — only then does `load` answer. */
export const isVirtual = (id: string): boolean =>
	id === resolved(CATALOGUES_ID) || id.startsWith(resolved(LOCALE_PREFIX));

/** The source `load` serves for a resolved `id`, from `loaded`; `undefined` for a locale it does not have. */
export function virtualModuleSource(
	id: string,
	loaded: LoadedCatalogues,
): string | undefined {
	if (id === resolved(CATALOGUES_ID)) return cataloguesModuleSource(loaded);
	const locale = id.slice(resolved(LOCALE_PREFIX).length);
	const catalogue = Object.hasOwn(loaded.catalogues, locale)
		? loaded.catalogues[locale]
		: undefined;
	return catalogue === undefined ? undefined : catalogueModuleSource(catalogue);
}

/**
 * The `resolveId` and `load` hooks that serve the modules for `locales`,
 * from `current`: the catalogues last loaded and checked, loaded first if
 * none were yet.
 */
export function virtualHooks(
	locales: readonly string[],
	current: () => Promise<LoadedCatalogues>,
) {
	return {
		resolveId(id: string) {
			return resolveVirtual(id, locales);
		},
		async load(id: string) {
			if (!isVirtual(id)) return undefined;
			return virtualModuleSource(id, await current());
		},
	};
}

/** In `vite dev`, after the catalogues changed and checked: drops the served modules from the module graph, and reloads the page. */
export function invalidateServed(
	server: ViteDevServer,
	locales: readonly string[],
): void {
	for (const id of servedIds(locales)) {
		const module = server.moduleGraph.getModuleById(id);
		if (module !== undefined) server.moduleGraph.invalidateModule(module);
	}
	server.ws.send({ type: 'full-reload' });
}

/** Where the types of the served modules go: beside `out`, `i18n.d.ts` -> `i18n.catalogues.d.ts`. */
export function virtualTypesFile(out: string): string {
	return `${out.slice(0, -'.d.ts'.length)}.catalogues.d.ts`;
}

/**
 * The declaration file of the served modules. A script, not a module — no
 * top-level `import` — because only a script declares a module: in a module
 * (as the file of `t`'s types is, to augment `@nxgt/i18n-vue`), a
 * `declare module` of a name that resolves to no file is an augmentation of
 * nothing, and TypeScript drops it without a word. Its first two lines are
 * every generated file's, so `writeTypes` guards it the same way.
 */
export function virtualTypesSource(fallbackLocale: string): string {
	return [
		`// Generated by @nxgt/i18n-vue from the ${fallbackLocale} catalogue.`,
		// The marker every generated file shares, whatever it types: what writeTypes checks.
		MARKER,
		'// The modules i18nTypes({ lazy: true }) serves. A script, not a module: only a script declares one.',
		'',
		`declare module '${CATALOGUES_ID}' {`,
		"\timport type { CatalogueLoaders, Catalogues, Locale } from '@nxgt/i18n-vue';",
		`\t/** The reference locale: its catalogue is in \`catalogues\`. */`,
		'\texport const fallbackLocale: Locale;',
		'\t/** Every locale, in the order i18nTypes was given them. */',
		'\texport const locales: readonly Locale[];',
		"\t/** The fallback locale's catalogue, inline. */",
		'\texport const catalogues: Catalogues;',
		'\t/** One loader per other locale, each its own chunk. */',
		'\texport const loaders: CatalogueLoaders;',
		'}',
		'',
		`declare module '${LOCALE_PREFIX}*' {`,
		"\timport type { Catalogue } from '@nxgt/i18n-vue';",
		'\tconst catalogue: Catalogue;',
		'\texport default catalogue;',
		'}',
		'',
	].join('\n');
}
