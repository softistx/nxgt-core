import type { Catalogue } from '../core/catalogues';
import { cookieSource } from './cookie-source';
import { CATALOGUE_STATE_KEY, STATE_KEY } from './state-key';

/** What the generated plugin of locales loaded on demand is made from. */
export interface LazyPluginSourceOptions {
	/** The catalogues loaded up front: the fallback locale's at least. */
	readonly catalogues: Readonly<Record<string, Catalogue>>;
	readonly fallbackLocale: string;
	readonly cookie: string;
	/** The module specifier of each other locale's catalogue, by locale. */
	readonly loaders: Readonly<Record<string, string>>;
	/**
	 * Every locale, in the configured order: the locale is resolved among
	 * them, and `pickLocale` breaks a tie — `pt` among `pt-PT` and `pt-BR` —
	 * by this order, so it must be the eager plugin's.
	 */
	readonly locales: readonly string[];
}

/**
 * The Nuxt plugin of `nxgtI18n: { lazy: true }`, as source: the catalogues of
 * `catalogues` inline, one dynamic `import()` per locale of `loaders` — so
 * the bundler makes each a chunk of its own — and an `async setup` that
 * awaits `setupLazyNuxtI18n`. Nuxt awaits a plugin that is not `parallel`
 * before the next one and before rendering, so the server renders in the
 * resolved locale. Every composable is called before the first `await`, and
 * `useHead` after it through `runWithContext`, as Nuxt's context is gone
 * once a plugin has awaited.
 */
export function lazyPluginSource(options: LazyPluginSourceOptions): string {
	return [
		'// Generated by @nxgt/i18n-vue/nuxt. Never edited.',
		"import { defineNuxtPlugin, useCookie, useHead, useRequestHeaders, useState } from '#imports';",
		"import { setupLazyNuxtI18n } from '@nxgt/i18n-vue/nuxt/runtime';",
		'',
		`const catalogues = ${JSON.stringify(options.catalogues)};`,
		'const loaders = {',
		...Object.entries(options.loaders).map(
			([locale, specifier]) =>
				`\t${JSON.stringify(locale)}: () => import(${JSON.stringify(specifier)}),`,
		),
		'};',
		`const locales = ${JSON.stringify(options.locales)};`,
		'',
		'export default defineNuxtPlugin({',
		"\tname: '@nxgt/i18n-vue',",
		"\tenforce: 'pre',",
		'\tasync setup(nuxtApp) {',
		"\t\t// Every composable before the first await: Nuxt's context is gone after it.",
		'\t\tconst header = import.meta.server',
		"\t\t\t? useRequestHeaders(['accept-language'])['accept-language']",
		'\t\t\t: undefined;',
		'\t\tconst i18n = await setupLazyNuxtI18n({',
		'\t\t\tcatalogues,',
		'\t\t\tloaders,',
		'\t\t\tlocales,',
		`\t\t\tfallbackLocale: ${JSON.stringify(options.fallbackLocale)},`,
		`\t\t\tcookie: ${cookieSource(options.cookie)},`,
		`\t\t\tstate: useState(${JSON.stringify(STATE_KEY)}),`,
		`\t\t\tcatalogue: useState(${JSON.stringify(CATALOGUE_STATE_KEY)}),`,
		'\t\t\trequested: () =>',
		'\t\t\t\timport.meta.server',
		'\t\t\t\t\t? header',
		"\t\t\t\t\t: typeof navigator === 'undefined' ? null : navigator.languages,",
		'\t\t});',
		'\t\tnuxtApp.vueApp.use(i18n);',
		'\t\t// After the await: a composable needs the context back.',
		'\t\tnuxtApp.runWithContext(() => useHead({ htmlAttrs: { lang: i18n.locale } }));',
		'\t},',
		'});',
		'',
	].join('\n');
}
